import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
export function validateReleases(manifest) {
  const releases = manifest?.releases;
  if (manifest?.schemaVersion !== 1 || !Array.isArray(releases) || !releases.length) throw new Error('Histórico de releases inválido.');
  const versions = new Set();
  releases.forEach((release, index) => {
    if (!/^\d+\.\d+\.\d+(?:-[a-z0-9]+(?:\.[a-z0-9]+)*)?$/.test(release.version) || versions.has(release.version)) throw new Error('Versão inválida ou repetida.');
    versions.add(release.version);
    if (release.number !== releases.length - index || !/^\d{4}-\d{2}-\d{2}$/.test(release.date) || !Number.isFinite(Date.parse(release.date)) || !release.title?.trim() || !release.changes?.length || release.changes.some(note => typeof note !== 'string' || !note.trim())) throw new Error('Metadados da release inválidos.');
  });
  return manifest;
}
export function compareVersions(left, right) {
  const split = version => { const [base, pre] = version.split('-'); return { base: base.split('.').map(Number), pre: pre?.split('.') }; };
  const a = split(left), b = split(right);
  for (let i = 0; i < 3; i++) if (a.base[i] !== b.base[i]) return a.base[i] - b.base[i];
  if (!a.pre || !b.pre) return Number(!a.pre) - Number(!b.pre);
  for (let i = 0; i < Math.max(a.pre.length, b.pre.length); i++) {
    const x = a.pre[i], y = b.pre[i];
    if (x === y) continue;
    if (x === undefined || y === undefined) return x === undefined ? -1 : 1;
    const nx = /^\d+$/.test(x), ny = /^\d+$/.test(y);
    if (nx && ny) return Number(x) - Number(y);
    if (nx !== ny) return nx ? -1 : 1;
    return x < y ? -1 : 1;
  }
  return 0;
}
export function nextRelease(manifest, { version, title, changes, date = new Date().toISOString().slice(0, 10) }) {
  validateReleases(manifest);
  const current = manifest.releases[0];
  const result = { schemaVersion: 1, releases: [{ version, number: current.number + 1, date, title, changes }, ...manifest.releases] };
  validateReleases(result);
  if (compareVersions(version, current.version) <= 0) throw new Error('A próxima versão deve ser maior que a atual.');
  return result;
}
export function releaseArtifacts(manifest) {
  validateReleases(manifest);
  return {
    'core/release-info.js': `// Generated by scripts/release.mjs from releases.json.\nexport const releaseHistory = ${JSON.stringify(manifest.releases, null, 2)};\nexport const currentRelease = releaseHistory[0];\n`,
    'public/release.json': JSON.stringify(manifest, null, 2) + '\n',
    'CHANGELOG.md': '# unkayOS — Changelog\n\nO contador de releases começa em 1 com a versão 2.0.0-alpha.2. Builds da mesma versão preservam o número; cada release preparada incrementa o contador.\n\n' + manifest.releases.map(release => `## ${release.version} · Release ${release.number} · ${release.date}\n\n${release.title}\n\n${release.changes.map(note => '- ' + note).join('\n')}\n`).join('\n')
  };
}
function main() {
  const mode = process.argv[2] || 'check';
  let manifest = JSON.parse(readFileSync(resolve(root, 'releases.json'), 'utf8'));
  if (mode === 'prepare') {
    const args = process.argv.slice(3);
    const value = flag => args.includes(flag) ? args[args.indexOf(flag) + 1] : undefined;
    manifest = nextRelease(manifest, { version: value('--version'), title: value('--title'), changes: args.flatMap((arg, index) => arg === '--note' ? [args[index + 1]] : []) });
    writeFileSync(resolve(root, 'releases.json'), JSON.stringify(manifest, null, 2) + '\n');
    for (const filename of ['package.json', 'package-lock.json']) {
      const pkg = JSON.parse(readFileSync(resolve(root, filename), 'utf8'));
      pkg.version = manifest.releases[0].version;
      if (pkg.packages?.['']) pkg.packages[''].version = pkg.version;
      writeFileSync(resolve(root, filename), JSON.stringify(pkg, null, 2) + '\n');
    }
  } else if (!['check', 'sync'].includes(mode)) throw new Error('Use release.mjs check | sync | prepare --version ... --title ... --note ...');
  const artifacts = releaseArtifacts(manifest);
  for (const [filename, source] of Object.entries(artifacts)) {
    if (mode === 'check') {
      if (readFileSync(resolve(root, filename), 'utf8').replaceAll('\r\n', '\n') !== source) throw new Error(`Artefato desatualizado: ${filename}. Execute npm run release:sync.`);
    } else writeFileSync(resolve(root, filename), source);
  }
  for (const filename of ['package.json', 'package-lock.json']) {
    if (JSON.parse(readFileSync(resolve(root, filename), 'utf8')).version !== manifest.releases[0].version) throw new Error(`Versão divergente: ${filename}.`);
  }
  console.log(`unkayOS ${manifest.releases[0].version} · release ${manifest.releases[0].number} (${mode})`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
