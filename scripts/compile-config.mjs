import { readFileSync, writeFileSync } from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const ajv = new Ajv2020({ strict: true, allErrors: true, code: { source: true, esm: true } });
const names = {
    deployment: 'deployment', plugin: 'plugin', emptyConfig: 'empty', httpAi: 'http-ai', rolePolicy: 'role-policy',
    gatewayIdentity: 'gateway-identity', gatewayAccess: 'gateway-access',
    // Private documents are validated by the Node gateway with the same generated code.
    server: 'server', accessPolicy: 'access-policy'
};
const exports = {};
for (const [name, file] of Object.entries(names)) {
    const schema = JSON.parse(readFileSync(new URL(`config/schemas/${file}.schema.json`, root), 'utf8'));
    ajv.addSchema(schema);
    exports[name] = schema.$id;
}
// Generated ESM needs no Ajv, eval, network schema resolution or bare imports in the browser.
const bundled = await build({
    stdin: { contents: standaloneCode(ajv, exports), resolveDir: fileURLToPath(root) },
    bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2022', legalComments: 'inline'
});
const output = '// @ts-nocheck\n// Generated by npm run config:compile. Do not edit.\n' + bundled.outputFiles[0].text;
const destination = new URL('core/host/config/validators.generated.js', root);
if (process.argv.includes('--check')) {
    if (readFileSync(destination, 'utf8') !== output) throw new Error('Config validators are stale. Run npm run config:compile.');
} else {
    writeFileSync(destination, output);
}
